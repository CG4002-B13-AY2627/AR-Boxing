#!/usr/bin/env python3
"""Embed an actual local file and its SHA256 into an Arduino header.

Run this on your laptop, then recompile/upload the sketch. The file bytes
reside in ESP32 flash; there is no laptop-to-Ultra96 bypass during the demo.
"""
import argparse
import hashlib
from pathlib import Path
import re


def embed(source, destination):
    source, destination = Path(source), Path(destination)
    data = source.read_bytes()
    if len(data) > 1024 * 1024:
        raise ValueError('file must be at most 1 MiB (also check available flash)')
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,31}', source.name):
        raise ValueError('use an ASCII filename of 1–32 letters/digits/underscore/dot/dash')
    digest = hashlib.sha256(data).digest()
    # Keep a one-byte backing array for a valid C++ definition for empty files.
    values = data if data else b'\0'
    rows = ['  ' + ', '.join(f'0x{b:02x}' for b in values[i:i+16]) + ','
            for i in range(0, len(values), 16)]
    destination.write_text(
        '// Generated by embed_file.py; do not edit by hand.\n'
        '#pragma once\n#include <Arduino.h>\n'
        f'const char FILE_NAME[] = "{source.name}";\n'
        f'const uint32_t FILE_SIZE = {len(data)};\n'
        'const uint8_t FILE_SHA256[32] = {\n  '
        + ', '.join(f'0x{b:02x}' for b in digest) + '\n};\n'
        'const uint8_t FILE_BYTES[] PROGMEM = {\n'
        + '\n'.join(rows) + '\n};\n', encoding='utf-8')
    print(f'Embedded {source.name}: {len(data)} bytes')
    print(f'Original SHA256: {digest.hex()}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('file')
    parser.add_argument('--output', default='ESP32_file_transfer/file_payload.h')
    args = parser.parse_args()
    embed(args.file, args.output)
