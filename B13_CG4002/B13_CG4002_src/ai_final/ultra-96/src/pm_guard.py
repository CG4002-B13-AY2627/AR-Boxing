import atexit
import json
import os
import signal
import subprocess

from u96_config import (
    DEADMAN_ARMED_NAME,
    DEADMAN_FIRED_NAME,
    DEADMAN_NAME,
    RESTORE_NAME,
    SNAPSHOT_NAME,
)


def give_back(path):
    """Un-root files written under sudo, so they are readable as xilinx."""
    uid, gid = os.environ.get("SUDO_UID"), os.environ.get("SUDO_GID")
    if not (uid and gid):
        return
    try:
        os.chown(path, int(uid), int(gid))
    except OSError:
        pass


def _script(path, lines):
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    path.chmod(0o755)
    give_back(path)


def write_restore(path, controls, snapshot):
    """A shell script that undoes everything, without needing this process.

    Written before the first knob is touched. Every other safety net here --
    the finally, the signal handlers, atexit -- assumes the process still
    exists to run it; `kill -9`, a power cut mid-sweep or a dropped SSH session
    do not grant that. This file is what is left on disk when none of them ran.
    """
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by pmanagement.py. Returns the board to the state it was",
        "# in before the run that wrote this file. Safe to run at any time,",
        "# and safe to run twice.",
        "set -u",
        "",
    ]
    for control in controls:
        lines.append(f"# {control.name}: {control.label_state(snapshot[control.name])}")
        lines.extend(control.restore_commands(snapshot[control.name]))
        lines.append("")
    lines.append('echo "board restored."')
    _script(path, lines)


def read_snapshot(directory):
    path = directory / SNAPSHOT_NAME
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


class Guard:
    def __init__(self, controls, directory):
        self.controls = list(controls)
        self.snapshot = {c.name: c.snapshot() for c in self.controls}
        self.failed = []
        self.active = True

        write_restore(directory / RESTORE_NAME, self.controls, self.snapshot)
        snapshot = directory / SNAPSHOT_NAME
        snapshot.write_text(json.dumps(self.snapshot, indent=2), encoding="utf-8")
        give_back(snapshot)

        self.previous = {}
        for name in ("SIGTERM", "SIGHUP"):
            sig = getattr(signal, name, None)
            if sig is None:
                continue
            try:
                self.previous[sig] = signal.signal(sig, self._on_signal)
            except (OSError, ValueError):
                pass
        atexit.register(self._at_exit)

    def restore(self, names=None):
        self.failed = []
        for control in self.controls:
            if names is not None and control.name not in names:
                continue
            try:
                control.restore(self.snapshot[control.name])
            except BaseException as exc:
                self.failed.append((control.name, exc))
        return not self.failed

    def keep(self):
        self.active = False
        self._release()

    def _release(self):
        for sig, handler in self.previous.items():
            try:
                signal.signal(sig, handler)
            except (OSError, ValueError):
                pass
        self.previous = {}

    def _at_exit(self):
        if self.active:
            self.restore()
            self.active = False

    def _on_signal(self, signum, _frame):
        self._at_exit()
        handler = self.previous.get(signum, signal.SIG_DFL)
        self._release()
        signal.signal(signum, handler)
        os.kill(os.getpid(), signum)

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self._at_exit()
        self._release()
        return False


class Deadman:
    def __init__(self, directory):
        self.script = directory / DEADMAN_NAME
        self.armed = directory / DEADMAN_ARMED_NAME
        self.fired = directory / DEADMAN_FIRED_NAME
        self.process = None

    def arm(self, controls, snapshot, seconds):
        self.disarm()
        lines = [
            "#!/usr/bin/env bash",
            "set -u",
            f"sleep {seconds:.0f}",
            f'[ -e "{self.armed}" ] || exit 0',
        ]
        for control in controls:
            lines.extend(control.restore_commands(snapshot[control.name]))
        lines += [f'rm -f "{self.armed}"', f'touch "{self.fired}"']
        _script(self.script, lines)

        self.fired.unlink(missing_ok=True)
        self.armed.touch()
        self.process = subprocess.Popen(
            ["bash", str(self.script)],
            start_new_session=True,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )

    def disarm(self):
        self.armed.unlink(missing_ok=True)
        if self.process is not None and self.process.poll() is None:
            try:
                os.killpg(self.process.pid, signal.SIGTERM)
            except OSError:
                pass
            self.process.wait()
        self.process = None
        fired = self.fired.exists()
        self.fired.unlink(missing_ok=True)
        return fired
