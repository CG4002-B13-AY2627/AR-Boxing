import export_config
import check_config

from extract import extract, file_sha256

def guard(filename):
    stem = filename.replace(".", "_").upper()
    return f"{export_config.INCLUDE_GUARD_PREFIX}{stem}"

def c_type(bit_width, signed):
    return f"ap_{'' if signed else 'u'}int<{bit_width}>"

def flatten(values):
    if not isinstance(values, list):
        return [values]

    flat = []

    for value in values:
        flat.extend(flatten(value))

    return flat

def padding(kernel):
    total = kernel - 1
    left = total // 2

    return left, total - left

def format_array(name, ctype, values, comment, per_line=12):
    flat = flatten(values)
    lines = [f"// {comment}", f"static const {ctype} {name}[{len(flat)}] = {{"]

    for start in range(0, len(flat), per_line):
        chunk = ", ".join(str(value) for value in flat[start:start + per_line])
        lines.append(f"    {chunk},")

    lines.append("};")

    return "\n".join(lines)

def provenance(meta, tool="emit.py"):
    """The comment block that ties a header back to one checkpoint."""
    return "\n".join([
        f"// Generated by {tool}. DO NOT EDIT.",
        f"// checkpoint  {meta['checkpoint']}",
        f"// sha256      {meta['sha256']}",
        f"// bit width   {meta['bit_width']}",
        # Derived per export, so every artefact says which width it was built
        # with rather than leaving it to be looked up.
        f"// accumulator {meta['accumulator_width']} bits",
        f"// torch       {meta['torch']}    brevitas {meta['brevitas']}",
    ])

def emit_weights(description):
    meta = description["meta"]
    width = meta["bit_width"]

    params_include = export_config.PARAMS_NAME.format(width)
    filename = export_config.WEIGHTS_NAME.format(width)
    name = guard(filename)

    parts = [
        provenance(meta),
        "",
        f"#ifndef {name}",
        f"#define {name}",
        "",
        f'#include "{params_include}"',
        "",
    ]

    for layer in description["layers"]:
        shape = layer["weight_shape"]

        if layer["kind"] == "conv":
            out_channels, in_channels, kernel = shape
            index = (
                f"({layer['name']}) [o][i][k] = "
                f"(o * {in_channels} + i) * {kernel} + k"
            )
            dimensions = f"out={out_channels}, in={in_channels}, k={kernel}"
        else:
            out_features, in_features = shape
            index = f"({layer['name']}) [o][i] = o * {in_features} + i"
            dimensions = f"out={out_features}, in={in_features}"

        parts.append(format_array(
            name=f"{layer['name']}_w",
            ctype="w_t",
            values=layer["weight"],
            comment=f"{dimensions}. Index {index}",
        ))
        parts.append("")

        parts.append(format_array(
            name=f"{layer['name']}_b",
            ctype="acc_t",
            values=layer["bias"],
            comment=(
                f"{layer['name']} bias, at the accumulator scale "
                f"2^{layer['accumulator_log2_scale']}"
            ),
        ))
        parts.append("")

    parts.append(f"#endif  // {name}")

    return "\n".join(parts) + "\n"

def emit_params(description):
    meta = description["meta"]
    width = meta["bit_width"]

    filename = export_config.PARAMS_NAME.format(width)
    name = guard(filename)

    parts = [
        provenance(meta),
        "",
        f"#ifndef {name}",
        f"#define {name}",
        "",
        "#include <ap_int.h>",
        "",
        "// The input arrives channel-major: in[c][t], index c * NN_WINDOW + t.",
        "// qacnn.py transposes (window, channels) -> (channels, window) before",
        "// quant_input, so this is the layout the model was trained on and the",
        "// layout the golden vectors are dumped in. The PS transposes the",
        "// sensor stream to match before the DMA; the PL never reorders.",
        "",
        f"#define NN_W        {width}",
        f"#define NN_ACC_W    {meta['accumulator_width']}",
        f"#define NN_WINDOW   {meta['window_size']}",
        f"#define NN_CH       {meta['num_channels']}",
        f"#define NN_CLASSES  {meta['num_classes']}",
        "",
        # The rounding rule is the one piece of the arithmetic the description
        # does not carry: extract.py emits shifts and clamps and says nothing
        # about how the shift rounds. int_model.py settled it empirically and
        # check_config.VERIFIED_ROUNDING records the answer.
        f"#define NN_ROUND_{check_config.VERIFIED_ROUNDING.upper()}",
        "",
        "// Class order, for the argmax on the PS.",
    ]

    for index, label in enumerate(meta["labels"]):
        parts.append(f"//   {index}  {label}")

    parts.append("")
    parts.append("// Activation types, one per quantizer, so nothing has to")
    parts.append("// assume two of them agree.")

    for activation, spec in description["activations"].items():
        parts.append(
            f"typedef {c_type(spec['bit_width'], spec['signed'])} "
            f"{activation}_t;  // scale 2^{spec['log2_scale']}"
        )

    parts.append(f"typedef {c_type(width, True)} w_t;")
    parts.append(f"typedef ap_int<{meta['accumulator_width']}> acc_t;")
    parts.append("")

    for layer in description["layers"]:
        prefix = layer["name"].upper()
        shape = layer["weight_shape"]

        parts.append(
            f"// {layer['name']}: {layer['input_activation']} -> "
            f"{layer['output_activation'] or 'raw logits'}, "
            f"{layer['terms']} terms, "
            f"accumulator needs {layer['accumulator_bits_required']} bits"
        )

        if layer["kind"] == "conv":
            out_channels, in_channels, kernel = shape
            pad_left, pad_right = padding(kernel)

            parts.append(f"#define {prefix}_OUT   {out_channels}")
            parts.append(f"#define {prefix}_IN    {in_channels}")
            parts.append(f"#define {prefix}_K     {kernel}")
            parts.append(f"#define {prefix}_PAD_L {pad_left}")
            parts.append(f"#define {prefix}_PAD_R {pad_right}")
        else:
            out_features, in_features = shape

            parts.append(f"#define {prefix}_OUT   {out_features}")
            parts.append(f"#define {prefix}_IN    {in_features}")

        if layer["shift"] is None:
            parts.append(
                f"#define {prefix}_OUT_LOG2_SCALE "
                f"{layer['accumulator_log2_scale']}"
            )
        else:
            parts.append(f"#define {prefix}_SHIFT {layer['shift']}")
            parts.append(f"#define {prefix}_LO    {layer['clamp_low']}")
            parts.append(f"#define {prefix}_HI    {layer['clamp_high']}")

        parts.append("")

    maxpool = description["maxpool"]

    parts.append("// max pool between conv1 and conv2. No quantizer, so no")
    parts.append("// shift and no clamp: max passes the scale through.")
    parts.append("// MAXPOOL_OUT is floor((NN_WINDOW - K) / STRIDE) + 1, which")
    parts.append("// is not NN_WINDOW / STRIDE once the kernel overlaps. It is")
    parts.append("// emitted so the C++ reads the length instead of deriving it.")
    parts.append(f"#define MAXPOOL_K      {maxpool['kernel']}")
    parts.append(f"#define MAXPOOL_STRIDE {maxpool['stride']}")
    parts.append(f"#define MAXPOOL_OUT    {maxpool['output_size']}")
    parts.append("")

    pool = description["global_pool"]

    parts.append(
        f"// global pool: {pool['input_activation']} -> "
        f"{pool['output_activation']}, sum {pool['size']} and shift once."
    )
    parts.append("// Summing then shifting once is not an optimisation, it is")
    parts.append("// what Brevitas does: dividing first and requantizing after")
    parts.append("// rounds twice and drifts an LSB. int_model.py checked this.")
    parts.append(f"#define POOL_SIZE  {pool['size']}")
    parts.append(f"#define POOL_SHIFT {pool['shift']}")
    parts.append(f"#define POOL_LO    {pool['clamp_low']}")
    parts.append(f"#define POOL_HI    {pool['clamp_high']}")
    parts.append("")
    parts.append(f"#endif  // {name}")

    return "\n".join(parts) + "\n"

def check_emittable(description):
    """Everything that must hold before a header is worth writing."""
    if export_config.EMIT_STYLE != "int":
        raise SystemExit(
            f"EMIT_STYLE is {export_config.EMIT_STYLE!r}; emit.py only renders "
            f"integers. The ap_fixed variant would have to re-derive every "
            f"binary point, which is the thing the shifts already encode."
        )

    # Without this the headers ship whatever rounding nn_infer.cpp happens to
    # implement, and a csim mismatch of one LSB is exactly the failure that is
    # hardest to attribute. check.py exists to fill this in.
    if check_config.VERIFIED_ROUNDING not in check_config.ROUNDING_MODES:
        raise SystemExit(
            f"check_config.VERIFIED_ROUNDING is "
            f"{check_config.VERIFIED_ROUNDING!r}. Run check.py, then record "
            f"the mode that gave zero mismatches before emitting headers."
        )

    # build/description_w{N}.json is gitignored and can outlive the checkpoint
    # it came from. Committing headers generated from a stale description is
    # the one mistake here that survives every check downstream of it.
    path, _ = export_config.selected_checkpoint()

    if description["meta"]["sha256"] != file_sha256(path):
        raise SystemExit(
            f"The description was extracted from a different checkpoint than "
            f"{path.name}. Re-run extract() rather than emitting this."
        )

    # extract() sizes acc_t to cover every dot product and the pool's sum; this
    # is the same check for the bias, which is declared as acc_t and would wrap
    # silently rather than fail to compile. It should now be unreachable, since
    # the derived width is taken from a bound that already includes the bias --
    # which is exactly why it is worth keeping. It is what would catch that
    # derivation going wrong.
    width = description["meta"]["accumulator_width"]
    limit = 2 ** (width - 1) - 1

    for layer in description["layers"]:
        peak = max(abs(value) for value in layer["bias"])

        if peak > limit:
            raise SystemExit(
                f"{layer['name']}: bias reaches {peak}, which does not fit the "
                f"derived {width}-bit accumulator."
            )

def emit_selected(description):
    """The header that records which width the export chose.

    params.hpp includes it to default NN_WIDTH, and the Tcl reads the same
    number, so the width has exactly one home on this side of the export and
    no hand-written file repeats it. -DNN_WIDTH=<n> still overrides it.
    """
    meta = description["meta"]
    name = guard(export_config.SELECTED_NAME)

    return "\n".join([
        provenance(meta),
        "",
        f"#ifndef {name}",
        f"#define {name}",
        "",
        "// The width the export selected, read off the checkpoint filename.",
        "// Consumed by params.hpp and by run_hls.tcl / block_design.tcl.",
        f"#define NN_WIDTH_SELECTED {meta['bit_width']}",
        "",
        f"#endif  // {name}",
        "",
    ])


def emit(description, out_dir=None):
    """Write the headers. Returns the paths, in the order they were written."""
    check_emittable(description)

    width = description["meta"]["bit_width"]
    out_dir = out_dir or export_config.OUT_DIR
    out_dir.mkdir(parents=True, exist_ok=True)

    written = []

    files = [
        (export_config.PARAMS_NAME.format(width), emit_params(description)),
        (export_config.WEIGHTS_NAME.format(width), emit_weights(description)),
    ]

    # A sweep export names its own width on the command line and must not
    # move the default; only the selected checkpoint gets to do that.
    if export_config.CHECKPOINT_OVERRIDE is None:
        files.append((export_config.SELECTED_NAME, emit_selected(description)))

    for filename, text in files:
        path = out_dir / filename

        with open(path, "w") as f:
            f.write(text)

        written.append(path)

    return written
